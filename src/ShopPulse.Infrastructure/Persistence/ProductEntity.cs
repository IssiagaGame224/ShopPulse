using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using ShopPulse.Domain;

namespace ShopPulse.Infrastructure.Persistence;

/// <summary>Entité de persistance : distincte du record Domain <see cref="Product"/>,
/// pour que le Domain ne référence jamais EF Core (règle NetArchTest).
/// La catégorie est une vraie relation (CategoryId → categories), pas une chaîne libre ;
/// le Domain, lui, continue de recevoir le NOM de la catégorie (projection).</summary>
public class ProductEntity
{
       public int Id { get; set; }
       public required string Name { get; set; }
       public int CategoryId { get; set; }
       public CategoryEntity Category { get; set; } = null!;
       public decimal Price { get; set; }
       public decimal? OldPrice { get; set; }
       public int Stock { get; set; }
       public required string ImageUrl { get; set; }
       public required string Description { get; set; }
       public required string Sku { get; set; }
       public List<string> Features { get; set; } = [];

       public Product ToDomain(double averageRating = 0, int reviewCount = 0) =>
              new(Id, Name, Category.Name, Price, Stock, ImageUrl, Description, Sku, OldPrice,
                     Features, averageRating, reviewCount);

       public static ProductEntity FromDomain(Product p) =>
              new() { Id = p.Id, Name = p.Name, CategoryId = CatalogSeed.CategoryIdOf(p.Category),
                      Price = p.Price, OldPrice = p.OldPrice, Stock = p.Stock, ImageUrl = p.ImageUrl,
                      Description = p.Description, Sku = p.Sku, Features = [.. p.Features] };
}

public class ProductEntityConfiguration : IEntityTypeConfiguration<ProductEntity>
{
       public void Configure(EntityTypeBuilder<ProductEntity> p)
       {
              p.ToTable("products");
              p.HasKey(x => x.Id);
              // Id généré par la base (identity PostgreSQL) : les ids du seed (1..200) sont
              // insérés explicitement (GENERATED BY DEFAULT), les créations back-office
              // reçoivent un id automatique.
              p.Property(x => x.Id).UseIdentityColumn();
              p.Property(x => x.Name).HasMaxLength(200).IsRequired();
              p.HasOne(x => x.Category).WithMany().HasForeignKey(x => x.CategoryId)
                     .OnDelete(DeleteBehavior.Restrict);      // jamais de suppression en cascade d'un catalogue
              p.Property(x => x.Price).HasPrecision(18, 2); // decimal : jamais de float pour l'argent
              p.Property(x => x.OldPrice).HasPrecision(18, 2);
              p.Property(x => x.ImageUrl).HasMaxLength(500).IsRequired();
              p.Property(x => x.Description).HasMaxLength(2000).IsRequired();
              p.Property(x => x.Sku).HasMaxLength(32).IsRequired();
              p.HasIndex(x => x.Sku).IsUnique();            // la référence est unique
              p.Property(x => x.Features).HasColumnType("jsonb");   // liste de specs, ordre préservé
              p.HasData(CatalogSeed.BuildProducts().Select(ProductEntity.FromDomain));
       }
}
